#!/usr/bin/env python3
# gen_names.py: the banner's names and descriptions, game/ach_names.inc from
# achievements.json (Sunshine's) and game/ach_eclipse_names.inc from
# eclipse.json (Super Mario Eclipse's). The launcher reads the JSON itself.
# Run from ext/achievements after changing either:
#   python3 tools/gen_names.py
import json, os, sys

here = os.path.dirname(os.path.abspath(__file__))
# what the game's system font draws (as the settings menu's hints say)
allowed = set("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 .,-'()")
for source, target in (('achievements.json', 'ach_names.inc'), ('eclipse.json', 'ach_eclipse_names.inc')):
    items = json.load(open(os.path.join(here, '..', source)))['achievements']
    out = [f'// Generated by tools/gen_names.py from {source}: do not edit.']
    for item in items:
        for key in ('title', 'description'):
            bad = set(item[key]) - allowed
            if bad:
                sys.exit(f"{source}: achievement {item['id']}'s {key} has {''.join(sorted(bad))!r}, which the game's font can't draw")
        out.append('{ %d, %s, %s },' % (item['id'], json.dumps(item['title']), json.dumps(item['description'])))
    open(os.path.join(here, '..', 'game', target), 'w').write('\n'.join(out) + '\n')
    print(source, len(items), 'names')
