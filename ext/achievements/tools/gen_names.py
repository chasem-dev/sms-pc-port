#!/usr/bin/env python3
# gen_names.py: game/ach_names.inc, the banner's names and descriptions, from
# achievements.json (the launcher reads that file itself). Run from
# ext/achievements after changing achievements.json:
#   python3 tools/gen_names.py
import json, os, sys

here = os.path.dirname(os.path.abspath(__file__))
items = json.load(open(os.path.join(here, '..', 'achievements.json')))['achievements']
# what the game's system font draws (as the settings menu's hints say)
allowed = set("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 .,-'()")
out = ['// Generated by tools/gen_names.py from achievements.json: do not edit.']
for item in items:
    for key in ('title', 'description'):
        bad = set(item[key]) - allowed
        if bad:
            sys.exit(f"achievement {item['id']}'s {key} has {''.join(sorted(bad))!r}, which the game's font can't draw")
    out.append('{ %d, %s, %s },' % (item['id'], json.dumps(item['title']), json.dumps(item['description'])))
open(os.path.join(here, '..', 'game', 'ach_names.inc'), 'w').write('\n'.join(out) + '\n')
print(len(items), 'names')
