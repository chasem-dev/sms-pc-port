#!/usr/bin/env python3
# gen_flag_rules.py REFERENCE_JSON OUT_INC : the Core achievements that only read the save file's flags, as a table
# for game/ach_flags.cpp. REFERENCE_JSON is the RetroAchievements set for the game (github.com/timenoe/RAScripts)
# read into JSON, kept outside this repository: only each achievement's raw condition is used (its GameCube
# addresses); the comments are our own descriptions, from ../achievements.json. Their flag addresses become TFlagManager
# flags: the card's bools start at 0x80578988 (flag 0x10000, a Shine's flag is 0x10000 + its id) and the stage's bools
# at 0x80578A6C (flag 0x50000), one bit per flag, low bit first.
import json, re, sys
CARD, STAGE = 0x578988, 0x578A6C
def flag(bit, addr):
    if CARD <= addr < 0x578A00: return 0x10000 + (addr - CARD) * 8 + bit
    if STAGE <= addr < STAGE + 13: return 0x50000 + (addr - STAGE) * 8 + bit
    raise ValueError(hex(addr))
def run(bit, addr, n): f = flag(bit, addr); return list(range(f, f + n))
A = {a['id']: a for a in json.load(open(sys.argv[1]))['achievements']}
OURS = {a['id']: a['description'] for a in json.load(open(__file__.rsplit('/', 2)[0] + '/achievements.json'))['achievements']}
rules = []  # (id, kind, need, flags, note)
for i, a in sorted(A.items()):
    raw = a.get('game_state', '').split('Raw:')[-1]
    m1 = re.fullmatch(r'\s*(?:inGame\(\) && )?regionBitflip\(\[(\d), (0x[0-9a-f]+)\]\)\s*', raw)
    mc = re.search(r'countRegionBits\(\[(\d), (0x[0-9a-f]+)\], (\d+)\)', raw)
    if i in (3, 4, 5, 6, 57):
        rules.append((i, 'SHINES', {3: 3, 4: 5, 5: 10, 6: 20, 57: 120}[i], [], 'Shines on the file'))
    elif i == 11:
        rules.append((i, 'ALL', 1, [0x10077], "the final Shine's flag (set as the ending plays)"))
    elif i == 10:
        rules.append((i, 'ALL', 7, [0x10000 + c * 10 + 6 for c in range(7)], "the 7 main courses' Episode 7 Shines"))
    elif i == 45:
        lst = [[5, 0x578993], [6, 0x578993], [7, 0x578993], [0, 0x578994], [1, 0x578994], [2, 0x578994], [3, 0x578994], [4, 0x578996], [5, 0x578996], [6, 0x578996]]
        rules.append((i, 'ALL', 10, [flag(b, x) for b, x in lst], "Delfino Plaza's 10 Shines"))
    elif i == 51:
        rules.append((i, 'ALL', 24, run(6, 0x578990, 16) + run(4, 0x578995, 8), "the boathouse's 24 trade Shines"))
    elif i == 58:
        blue = []
        f = flag(2, 0x57899d)
        for c in range(7): blue += list(range(f + c * 50, f + c * 50 + 30))
        blue += run(1, 0x578997, 19) + run(4, 0x5789cb, 10) + run(0, 0x578997, 1)
        rules.append((i, 'ALL', 240, blue, 'every blue coin'))
    elif i == 60:
        rules.append((i, 'ALL', 2, [flag(5, 0x578a6d), 0x10077], "a Pianta's shirt (the stage flag also used by sunglasses), after the ending"))
    elif mc and i not in (70, 74, 75):
        b, x, n = int(mc.group(1)), int(mc.group(2), 16), int(mc.group(3))
        rules.append((i, 'ALL', n, run(b, x, n), OURS[i]))
    elif m1:
        rules.append((i, 'ALL', 1, [flag(int(m1.group(1)), int(m1.group(2), 16))], OURS[i]))
ids = [r[0] for r in rules]
out = ['// Generated by ext/achievements/tools/gen_flag_rules.py from the reference set: do not edit by hand.',
       '// { achievement, kind, how many of the flags, the flags... } (FLAGS_SHINES: the Shine count instead).']
pool = []
for i, kind, need, flags, note in rules:
    start = len(pool); pool += flags
    out.append(f'{{ {i:3d}, {"FLAGS_SHINES" if kind == "SHINES" else "FLAGS_ALL"}, {need:3d}, {start:4d}, {len(flags):3d} }}, // {note}')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n#define ACH_FLAG_POOL ' + ', '.join(hex(f) for f in pool) + '\n')
print(len(rules), 'rules,', len(pool), 'flags; ids:', ids)
